// After `vite build`: write dist/sw.js, a service worker that precaches every file in dist/,
// so the app works offline (on the piano, away from Wi-Fi) once it has loaded. The cache
// name is a hash of the files, so each build replaces the old cache.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = fileURLToPath(new URL("../dist", import.meta.url));
const files: string[] = [];
const walk = (d: string) => {
  for (const f of readdirSync(d).sort()) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(relative(DIST, p).split(sep).join("/"));
  }
};
walk(DIST);
const assets = files.filter((f) => f !== "sw.js");
const hash = createHash("sha256");
for (const f of assets) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest("hex").slice(0, 12);
const urls = ["./", ...assets.filter((f) => f !== "index.html").map((f) => `./${f}`)];

writeFileSync(
  join(DIST, "sw.js"),
  `// Generated by scripts/build-sw.ts. Precache everything; cache-first; the app shell for navigations.
const CACHE = "zelda-piano-${version}";
const URLS = ${JSON.stringify(urls)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("zelda-piano-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  if (req.mode === "navigate") {
    e.respondWith(fetch(req).catch(() => caches.match("./", { ignoreSearch: true })));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`,
);
console.log(`[sw] ${urls.length} files precached as zelda-piano-${version}`);
